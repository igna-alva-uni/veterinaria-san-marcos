BEGIN;

CREATE SCHEMA pacientes;
SET LOCAL search_path TO pacientes;

CREATE TABLE pacientes (
    id_paciente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    especie VARCHAR(30) NOT NULL,
    raza VARCHAR(50),
    fecha_nacimiento DATE,
    peso_kg NUMERIC(5,2) CHECK (peso_kg > 0),
    genero CHAR(1) CHECK (genero IN ('M', 'F')),
    id_dueno BIGINT NOT NULL,
    anotaciones TEXT,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE historial_vacunas (
    id_vacuna BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES pacientes (id_paciente),
    nombre_vacuna VARCHAR(50) NOT NULL,
    fecha_aplicacion DATE NOT NULL,
    fecha_vencimiento DATE CHECK (fecha_vencimiento >= fecha_aplicacion)
);

CREATE TABLE atenciones_clinicas (
    id_atencion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES pacientes (id_paciente),
    id_veterinario BIGINT NOT NULL,
    fecha_atencion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo VARCHAR(255),
    diagnostico TEXT,
    tratamiento_medicamentos TEXT
);

CREATE INDEX idx_pacientes_dueno ON pacientes (id_dueno);
CREATE INDEX idx_vacunas_paciente ON historial_vacunas (id_paciente);
CREATE INDEX idx_atenciones_paciente ON atenciones_clinicas (id_paciente);

GRANT USAGE ON SCHEMA pacientes TO app_pacientes;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA pacientes TO app_pacientes;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA pacientes TO app_pacientes;

COMMIT;
