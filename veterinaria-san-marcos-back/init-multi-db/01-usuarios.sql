BEGIN;

CREATE SCHEMA usuarios;
SET LOCAL search_path TO usuarios;

CREATE TABLE usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run VARCHAR(12) NOT NULL UNIQUE,
    nombre VARCHAR(50) NOT NULL,
    apellido VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL
        CHECK (rol IN ('ADMINISTRADOR', 'RECEPCIONISTA', 'VETERINARIO', 'DUENO')),
    telefono VARCHAR(15),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

GRANT USAGE ON SCHEMA usuarios TO app_usuarios;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA usuarios TO app_usuarios;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA usuarios TO app_usuarios;

COMMIT;
