CREATE TABLE catalogo_servicios (
    codigo_servicio VARCHAR(10) PRIMARY KEY,
    nombre_servicio VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) NOT NULL,
    especie_permitida VARCHAR(50) NOT NULL DEFAULT 'TODAS',
    duracion_minutos INTEGER NOT NULL CHECK (duracion_minutos > 0),
    precio NUMERIC(12,0) NOT NULL CHECK (precio >= 0),
    comentarios TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE citas (
    id_cita BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMPTZ NOT NULL,
    duracion_minutos INTEGER NOT NULL CHECK (duracion_minutos > 0),
    precio_acordado NUMERIC(12,0) NOT NULL CHECK (precio_acordado >= 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'SOLICITADA'
        CHECK (estado IN ('SOLICITADA', 'CONFIRMADA', 'REAGENDADA', 'COMPLETADA', 'CANCELADA')),
    pago_estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (pago_estado IN ('PENDIENTE', 'PARCIAL', 'COMPLETO')),
    codigo_servicio VARCHAR(10) NOT NULL REFERENCES catalogo_servicios (codigo_servicio),
    id_paciente BIGINT NOT NULL,
    id_dueno BIGINT NOT NULL,
    id_veterinario BIGINT,
    comentarios TEXT,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_citas_fecha ON citas (fecha_hora);
CREATE INDEX idx_citas_dueno_fecha ON citas (id_dueno, fecha_hora);
CREATE INDEX idx_citas_paciente ON citas (id_paciente);

