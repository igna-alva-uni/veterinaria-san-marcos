-- Tienda online (EP3): productos con stock y pedidos generados desde el carrito.
CREATE TABLE productos (
    codigo_producto VARCHAR(10) PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) NOT NULL,
    principio_activo VARCHAR(100),
    presentacion VARCHAR(100),
    especie_permitida VARCHAR(50) NOT NULL DEFAULT 'TODAS',
    stock INTEGER NOT NULL CHECK (stock >= 0),
    precio NUMERIC(12,0) NOT NULL CHECK (precio >= 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE pedidos (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(20) NOT NULL UNIQUE,
    id_usuario BIGINT NOT NULL,
    nombre_cliente VARCHAR(100) NOT NULL,
    correo_cliente VARCHAR(100) NOT NULL,
    telefono_cliente VARCHAR(20),
    direccion VARCHAR(150),
    comuna VARCHAR(60),
    observaciones TEXT,
    subtotal_productos NUMERIC(12,0) NOT NULL DEFAULT 0 CHECK (subtotal_productos >= 0),
    subtotal_servicios NUMERIC(12,0) NOT NULL DEFAULT 0 CHECK (subtotal_servicios >= 0),
    total NUMERIC(12,0) NOT NULL CHECK (total >= 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'CONFIRMADO', 'ENTREGADO', 'CANCELADO')),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pedido_detalle (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedidos (id_pedido) ON DELETE CASCADE,
    tipo_item VARCHAR(10) NOT NULL CHECK (tipo_item IN ('PRODUCTO', 'SERVICIO')),
    codigo_item VARCHAR(10) NOT NULL,
    nombre_item VARCHAR(100) NOT NULL,
    precio_unitario NUMERIC(12,0) NOT NULL CHECK (precio_unitario >= 0),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    subtotal NUMERIC(12,0) NOT NULL CHECK (subtotal >= 0)
);

CREATE INDEX idx_pedidos_usuario ON pedidos (id_usuario, fecha_creacion);
CREATE INDEX idx_detalle_pedido ON pedido_detalle (id_pedido);
CREATE INDEX idx_detalle_item ON pedido_detalle (tipo_item, codigo_item);

